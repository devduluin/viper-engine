import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createHttpServer } from '../../../src/entrypoints/http/server.js';
import { parseId } from '../../../src/contracts/identity/ids.js';
import { parseJsonObject } from '../../../src/contracts/messages/json.js';
import { ApiFailure } from '../../../src/contracts/api/failure.js';
import { HTTP_ROUTES } from '../../../src/entrypoints/http/routes.js';
import { OPENAPI_DOCUMENT } from '../../../src/contracts/api/openapi.js';
import { assertValid } from '../api/validate.js';

function server() {
  let count = 0;
  const app = createHttpServer({ execute: async () => { count += 1; throw new Error('PRIVATE_SQL_ERROR'); } },
    { requestBytes: 1024, authenticate: async token => token === 'valid' ? {
      actorId: parseId('actor', 'actor'), appId: parseId('app', 'app') } : undefined });
  return { app, calls: () => count };
}
const auth = { authorization: 'Bearer valid' };

test('all non-streaming OpenAPI operations have concrete HTTP routes', () => {
  const paths = parseJsonObject(OPENAPI_DOCUMENT['paths']);
  const operations = Object.values(paths).flatMap(path => Object.values(parseJsonObject(path)).map(operation => parseJsonObject(operation)['operationId']))
    .filter(operation => operation !== 'streamRunEvents').sort();
  assert.deepEqual(HTTP_ROUTES.map(route => route.operation).sort(), operations);
});

test('unauthenticated ingress cannot reach application and request IDs are generated by server', async () => {
  const { app, calls } = server();
  try {
    for (const authorization of [undefined, 'Bearer invalid', 'Basic valid', 'Bearer valid,other']) {
      const response = await app.inject({ method: 'POST', url: '/api/v1/conversations', payload: {},
        headers: { ...(authorization === undefined ? {} : { authorization }), 'x-request-id': 'ATTACKER_REQUEST_ID' } });
      assert.equal(response.statusCode, 401);
      assertValid('ErrorResponse', response.json());
      assert.equal(response.headers['www-authenticate'], 'Bearer');
      assert.ok(!response.body.includes('ATTACKER_REQUEST_ID'));
    }
    assert.equal(calls(), 0);
  } finally { await app.close(); }
});

test('authority injection, malformed JSON, depth, bytes, queries and missing idempotency fail before use case', async () => {
  const { app, calls } = server();
  try {
    const cases = [
      { url: '/api/v1/conversations', payload: { actorId: 'foreign' } },
      { url: '/api/v1/conversations/c/runs', payload: { input: { content: [{ type: 'text', text: 'Hi' }] } } },
      { url: '/api/v1/conversations/c/runs', payload: { role: 'system', input: { content: [{ type: 'text', text: 'Hi' }] } } },
      { url: '/api/v1/conversations', payload: '{broken', headers: { 'content-type': 'application/json' } },
      { url: '/api/v1/conversations', payload: { title: 'x'.repeat(2000) }, status: 413 },
      { url: '/api/v1/conversations/c/runs', payload: { input: { content: [{ type: 'json', data: JSON.parse('['.repeat(40) + '0' + ']'.repeat(40)) }] } },
        headers: { 'idempotency-key': 'k' } },
    ];
    for (const item of cases) {
      const response = await app.inject({ method: 'POST', url: item.url, payload: item.payload, headers: { ...auth, ...item.headers } });
      assert.equal(response.statusCode, item.status ?? 400, `${item.url} ${JSON.stringify(item.payload)} ${response.body}`); assertValid('ErrorResponse', response.json());
    }
    for (const suffix of ['?limit=0', '?limit=1&limit=2', '?actorId=other', '?cursor=bad.dot', '?limit=1.1']) {
      const response = await app.inject({ method: 'GET', url: `/api/v1/conversations/c${suffix}`, headers: auth });
      assert.equal(response.statusCode, 400); assertValid('ErrorResponse', response.json());
    }
    assert.equal(calls(), 0);
  } finally { await app.close(); }
});

test('application/infrastructure failures use allowlisted error envelopes without private details', async () => {
  const { app } = server();
  try {
    const response = await app.inject({ method: 'POST', url: '/api/v1/conversations', payload: {}, headers: auth });
    assert.equal(response.statusCode, 500); assertValid('ErrorResponse', response.json());
    assert.ok(!response.body.includes('PRIVATE_SQL_ERROR'));
    assert.equal(parseJsonObject(parseJsonObject(response.json())['error'])['code'], 'INTERNAL_ERROR');
    assert.equal((await app.inject({ method: 'GET', url: '/missing', headers: auth })).statusCode, 404);
  } finally { await app.close(); }
});

test('revision conflicts preserve actionable current revision and outgoing private fields fail closed', async () => {
  for (const execute of [async () => { throw new ApiFailure('REVISION_CONFLICT', { currentRevision: 5, action: 'refresh_revision' }); },
    async () => ({ schemaVersion: 1, secret_ref: 'PRIVATE_SECRET' })]) {
    const app = createHttpServer({ execute }, { requestBytes: 1024,
      authenticate: async () => ({ actorId: parseId('actor', 'a'), appId: parseId('app', 'p') }) });
    try {
      const response = await app.inject({ method: 'GET', url: '/api/v1/capabilities', headers: auth });
      assert.ok([409, 500].includes(response.statusCode)); assertValid('ErrorResponse', response.json());
      assert.ok(!response.body.includes('PRIVATE_SECRET'));
    } finally { await app.close(); }
  }
});
